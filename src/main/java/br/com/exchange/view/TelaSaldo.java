    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        String senha = new String(pwdSenha.getPassword());
        pwdSenha.setText("");

        try {
            // A consulta confirma a senha e lê os saldos atuais.
            Investidor investidor = controller.consultarSaldo(investidorId, senha);
            Carteira carteira = investidor.getCarteira();

            String mensagem = "Nome: " + investidor.getNome()
                    + "\nCPF: " + investidor.getCpf()
                    + "\nReais: R$ " + carteira.getSaldoReais().toPlainString()
                    + "\nBitcoin: " + carteira.getSaldoBitcoin().toPlainString()
                    + "\nEthereum: " + carteira.getSaldoEthereum().toPlainString()
                    + "\nRipple: " + carteira.getSaldoRipple().toPlainString();

            JOptionPane.showMessageDialog(this, mensagem);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnConsultarActionPerformed


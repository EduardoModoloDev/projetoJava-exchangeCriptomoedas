    private void btnValidarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidarActionPerformed
            String senha = new String(pwdSenha.getPassword());
    pwdSenha.setText("");

    try {
        investidores.validarSenha(investidorId, senha);
        List<Moedas> moedas = mercado.consultarCotacoes();

        StringBuilder texto = new StringBuilder();
        for (Moedas moeda : moedas) {
            texto.append(moeda.getNome()).append(" (")
                    .append(moeda.getSigla()).append("): R$ ")
                    .append(moeda.getCotacao().toPlainString()).append('\n');
        }
        txaCotacoes.setText(texto.toString());

        // Libera a compra quando a senha e a consulta deram certo.
        cmbMoeda.setEnabled(true);
        txtValor.setEnabled(true);
        btnConfirmar.setEnabled(true);
        pwdSenha.setEnabled(false);
        btnValidar.setEnabled(false);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnValidarActionPerformed

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
            try {
        String sigla = (String) cmbMoeda.getSelectedItem();
        String texto = txtValor.getText().trim().replace(',', '.');
        BigDecimal valor = new BigDecimal(texto);

        // A compra e as taxas são calculadas pelo controller.
        Carteira carteira = mercado.comprar(investidorId, sigla, valor);

        String mensagem = "Compra realizada."
                + "\nReais: R$ " + carteira.getSaldoReais().toPlainString()
                + "\nBitcoin: " + carteira.getSaldoBitcoin().toPlainString()
                + "\nEthereum: " + carteira.getSaldoEthereum().toPlainString()
                + "\nRipple: " + carteira.getSaldoRipple().toPlainString();

        JOptionPane.showMessageDialog(this, mensagem);
        dispose();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Valor inválido");
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnConfirmarActionPerformed


    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
            String senha = new String(pwdSenha.getPassword());
    pwdSenha.setText("");
    txaExtrato.setText("");

    try {
        List<Operacao> operacoes = controller.consultarExtrato(investidorId, senha);

        if (operacoes.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nenhuma operação registrada.");
            return;
        }

        // Cada operação do Model ocupa uma linha.
        StringBuilder texto = new StringBuilder();
        for (Operacao operacao : operacoes) {
            texto.append(operacao.toString()).append('\n');
        }

        txaExtrato.setText(texto.toString());
        txaExtrato.setCaretPosition(0);
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnConsultarActionPerformed


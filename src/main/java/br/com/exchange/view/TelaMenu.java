    private void btnAtualizarCotacaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarCotacaoActionPerformed
        try {
        // O controller atualiza as três cotações e devolve os valores salvos.
        List<Moedas> moedas = mercado.atualizarCotacoes();
        StringBuilder mensagem = new StringBuilder("Cotações atualizadas:\n");

        for (Moedas moeda : moedas) {
            mensagem.append(moeda.getNome()).append(" (")
                    .append(moeda.getSigla()).append("): R$ ")
                    .append(moeda.getCotacao().toPlainString()).append('\n');
        }

        JOptionPane.showMessageDialog(this, mensagem.toString());
    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnAtualizarCotacaoActionPerformed


    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        String cpf = txtCpf.getText();
        String senha = new String(pwdSenha.getPassword());
        pwdSenha.setText("");

        try {
            // O controller confere o formato e autentica o investidor.
            Investidor investidor = controller.autenticar(cpf, senha);

            // As próximas telas recebem apenas o ID do investidor.
            new TelaMenu(investidor.getId()).setVisible(true);
            dispose();
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnEntrarActionPerformed

